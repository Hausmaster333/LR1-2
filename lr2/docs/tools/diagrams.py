# Схемы раздела «Дизайн» ЛР-2: сущности (docs/entities) и архитектура (docs/architecture).
# box(ключ, x центра, y центра, ширина, текст), edge(откуда, куда, подпись, at=(сдвиг x, сдвиг y) подписи)
from svgkit import Diagram


def entities(path):
    d = Diagram(1260, 540)
    d.box("vfs", 540, 60, 310, "Виртуальная файловая система", main=True)
    d.box("set", 1080, 60, 220, "Тестовый набор", note="сгенерированные данные", h=56)
    d.box("dir", 230, 200, 160, "Каталог")
    d.box("path", 540, 200, 140, "Путь")
    d.box("index", 860, 200, 150, "Индекс")
    d.box("file", 230, 350, 140, "Файл")
    d.box("name", 540, 350, 220, "Имя и расширение")
    d.box("query", 860, 350, 200, "Поисковый запрос")
    d.box("method", 1140, 350, 180, "Способ поиска", note="обход или индекс", h=56)
    d.box("content", 230, 500, 170, "Содержимое", note="размер и данные", h=56)
    d.box("real", 540, 500, 240, "Реальный файл на диске")
    d.box("result", 860, 500, 220, "Результат поиска", note="файлы и время", h=56)
    d.box("bench", 1140, 500, 170, "Замер", note="построение и поиск", h=56)

    d.edge("vfs", "dir", "корневой\nкаталог «/»", at=(-14, -6), anchor="end")
    d.edge("vfs", "index", "поддерживает\nв согласии с деревом", at=(16, -8), anchor="start")
    d.edge("set", "vfs", "добавляется в", at=(0, -14))
    # Каталог содержит каталоги: петля слева от блока
    d.edge("dir", "dir", "содержит\nкаталоги", at=(-8, 0), anchor="end", via=[(180, 140), (110, 140), (110, 200)])
    d.edge("dir", "file", "содержит файлы", at=(10, 0), anchor="start")
    d.edge("path", "dir", "указывает на\nкаталог или файл", at=(0, -24))
    d.edge("path", "file")
    d.edge("file", "name", "имеет", at=(0, -14))
    d.edge("index", "name", "ключи", at=(14, 0), anchor="start")
    d.edge("index", "file", "ссылается на файлы,\nне владея ими", at=(0, 0))
    d.edge("query", "name", "по имени\nили расширению", at=(0, -24))
    d.edge("query", "method", "одним из", at=(0, -14))
    d.edge("query", "result", "даёт", at=(10, 0), anchor="start")
    d.edge("file", "content", "имеет", at=(10, 0), anchor="start")
    d.edge("content", "real", "берётся из,\nтолько чтение", at=(0, -24))
    d.edge("bench", "method", "сравнивает\nдва способа", at=(10, 0), anchor="start")
    d.save(path)


def architecture(path):
    a = Diagram(1240, 590)
    a.panel(20, 20, 880, 130, "Интерфейс и точки входа")
    a.panel(930, 20, 290, 130, "Сторонние библиотеки")
    a.panel(20, 190, 880, 230, "Прикладная логика")
    a.panel(930, 190, 290, 230, "Внешняя система")
    a.panel(20, 460, 1200, 115, "Собственные библиотеки")

    a.box("tests", 140, 95, 190, "Модульные тесты", h=56, note="консоль")
    a.box("cli", 420, 95, 220, "Консольные замеры", h=56, note="консоль")
    a.box("gui", 740, 95, 240, "Графическая оболочка", h=56, note="проводник, поиск, замеры")
    a.box("gfx", 1075, 95, 250, "Графика и окна", h=56, note="окна, виджеты, графики")
    a.box("bench", 420, 262, 220, "Замеры", h=56, note="прогоны, CSV")
    a.box("vfs", 740, 262, 240, "Виртуальная ФС", h=56, main=True, note="каталоги, файлы, пути")
    a.box("index", 420, 362, 240, "Индекс файлов", h=56, note="имя, расширение → файлы")
    a.box("sources", 740, 362, 240, "Источники содержимого", h=56, note="реальные и сгенерированные")
    a.box("realfs", 1075, 362, 230, "Реальная ФС", h=56, note="только чтение", external=True)
    a.box("dict", 270, 528, 260, "Словарь на AVL-дереве", h=56, note="из ЛР-1")
    a.box("coll", 620, 528, 230, "Базовые коллекции", h=56, note="массив, перебор")
    a.box("mem", 960, 528, 260, "Управление памятью", h=56, note="умные указатели из ДЗ-1")

    a.edge("cli", "bench", "параметры", at=(-10, -8), anchor="end")
    a.edge("gui", "bench", "запуск,\nотмена", at=(-18, -10), anchor="end")
    a.edge("gui", "vfs", "операции, поиск,\nгенерация", at=(10, -8), anchor="start")
    a.edge("gui", "gfx")
    a.edge("bench", "vfs", "свои ФС", at=(0, -14))
    a.edge("vfs", "index", "обновляет при\nкаждом изменении", at=(-24, -12), anchor="end")
    a.edge("vfs", "sources", "содержимое", at=(10, 0), anchor="start")
    a.edge("sources", "realfs", "читает", at=(0, -14))
    # Тесты проверяют весь слой логики, библиотеки нужны всем компонентам логики
    a.arrow([(140, 123), (140, 188)], dashed=True)
    a.label(152, 162, "проверяют логику", "start")
    a.arrow([(140, 420), (140, 458)], dashed=True)
    a.label(152, 440, "все компоненты логики", "start")
    a.save(path)


def draw(docs):
    entities(docs / "entities.svg")
    architecture(docs / "architecture.svg")
