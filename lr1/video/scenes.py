def title_card(title, subtitle, extra=None):
    def draw(img, box, p):
        d = ImageDraw.Draw(img)
        x0, y0, x1, y1 = box
        d.rectangle([0, 0, x1, 8], fill=BLUE)
        text_center(d, ((x0 + x1) / 2, 420), title, Fonts.get("bold", 84), TEXT)
        text_center(d, ((x0 + x1) / 2, 530), subtitle, Fonts.get("regular", 40), DIM)
        if extra:
            y = 640
            for line in extra:
                text_center(d, ((x0 + x1) / 2, y), line, Fonts.get("regular", 32), BLUE)
                y += 52
    return draw


